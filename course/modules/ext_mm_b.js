  // (б) Простая и логарифмическая доходность
  function wReturns(root) {
    let seed = 7;
    const ss = U.slider(root, { label: "дневной разброс σ, %", min: 0.2, max: 8, step: 0.1, value: 2, fmt: (v) => nf(v, 1), onInput: () => draw() });
    const sn = U.slider(root, { label: "число дней", min: 5, max: 60, step: 1, value: 20, fmt: (v) => nf(v, 0), onInput: () => draw() });
    const sa = U.slider(root, { label: "размах для примера «вверх на a%, вниз на a%»", min: 1, max: 60, step: 1, value: 10, fmt: (v) => nf(v, 0) + "%", onInput: () => draw() });
    const bt = row(root);
    U.button(bt, "Новая серия", () => { seed += 1; draw(); });
    const cv = U.canvas(root, 640, 320), out = U.output(root);
    function draw() {
      const sig = ss.get() / 100, n = sn.get(), a = sa.get() / 100;
      const rng = Course.rand.seeded(seed * 7919 + 3);
      let prod = 1, sumS = 0, sumL = 0;
      const xs = [0], tr = [0], sm = [0], lg = [0];
      for (let i = 1; i <= n; i++) {
        const r = Math.max(-0.9, sig * Course.rand.normal(rng));
        prod *= 1 + r; sumS += r; sumL += Math.log(1 + r);
        xs.push(i); tr.push((prod - 1) * 100); sm.push(sumS * 100); lg.push(sumL * 100);
      }
      Course.plot.line(cv, {
        title: "Накопленная доходность за " + n + " дней, %", xlabel: "день", ylabel: "%",
        series: [
          { x: xs, y: tr, label: "настоящая: (1+r1)...(1+rn) - 1" },
          { x: xs, y: sm, label: "сумма простых r (приблизительно)", dash: [5, 4] },
          { x: xs, y: lg, label: "сумма ln(1+r)", color: col("--c3") }
        ]
      });
      const exact = (prod - 1) * 100, back = (Math.exp(sumL) - 1) * 100;
      const two = (1 + a) * (1 - a), twoLog = Math.log(1 + a) + Math.log(1 - a);
      out.innerHTML =
        "Настоящая доходность за период: <b>" + nf(exact, 2) + "%</b>. Сумма простых доходностей: <b>" + nf(sumS * 100, 2) + "%</b> (ошибка " + nf(sumS * 100 - exact, 2) + " п.п.). " +
        "Сумма лог-доходностей: <b>" + nf(sumL * 100, 2) + "%</b>, и e<sup>сумма</sup> - 1 = <b>" + nf(back, 2) + "%</b> - совпадает с настоящей (аддитивность лог-доходностей).<br>" +
        "Пример: +" + nf(a * 100, 0) + "%, затем -" + nf(a * 100, 0) + "%. Цена 100 &rarr; <b>" + nf(100 * two, 2) + "</b>. Простые доходности в сумме дают 0%, лог-доходности: " + nf(Math.log(1 + a) * 100, 2) + "% + (" + nf(Math.log(1 - a) * 100, 2) + "%) = <b>" + nf(twoLog * 100, 2) + "%</b> = ln(" + nf(two, 4) + "). Чем больше размах, тем сильнее простая сумма врёт.";
    }
    draw();
  }

